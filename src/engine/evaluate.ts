/**
 * 从白方视角评估局面（centipawns）。正数=白优，负数=黑优。
 * 评估项：子力价值 + 位置价值。将死/被将死由搜索层单独处理。
 */
export function evaluateBoard(chess: Chess): number {
  const board = chess.board();
  let score = 0;
  for (let r = 0; r < 8; r++) {
    for (let f = 0; f < 8; f++) {
      const piece = board[r][f];
      if (!piece) continue;
      const idx = r * 8 + f; // 白方视角：r=0 是第 8 行
      const base = PIECE_VALUE[piece.type];
      const pstWhite = PST[piece.type][idx];
      if (piece.color === 'w') {
        score += base + pstWhite;
      } else {
        // 黑方使用镜像索引
        const mirrored = (7 - r) * 8 + f;
        score -= base + PST[piece.type][mirrored];
      }
    }
  }
  return score;
}

/** 将评估转换为"当前行棋方"视角（正数=当前方占优）。 */
export function relativeEval(chess: Chess, turn: Color): number {
  const s = evaluateBoard(chess);
  return turn === 'w' ? s : -s;
}
